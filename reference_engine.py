CASE = 입력(
    출생연=1990, 임용=(2019, 3), 퇴직=(2047, 8),
    기준소득월액=4_300_000, 군복무=((2009, 6), (2011, 3)),
    일기간소득인정=True, 조기수령=False,
)

# TypeScript 포팅 후 아래 값과 대조할 것 (기준 가정: r=2.3%, p=2.1%, g=1.5%)
EXPECTED = {
    "재직총년": 30.33, "이행률": 1.0084,
    "월연금_원": 4_874_116, "허용오차": 2_000,   # 군복무_평균산입=True 기준
    "역전방지상한적용": True,
    "개시연": 2055, "무연금년": 8,
    # 미확정 항목에 따른 감도 (기준 가정 하에서)
    "감도": {"군복무_평균산입=False": 4_935_000, "일기간소득인정=False": 4_741_000},
}

if __name__ == "__main__":
    load_인상률()
    res = 계산(CASE)
    print(f"재직 {res['재직']['총년']:.2f}년 "
          f"(1기간 {res['재직']['1기간']:.2f} / 2기간 {res['재직']['2기간']:.2f} / 3기간 {res['재직']['3기간']:.2f})")
    print(f"이행률 {res['이행률']*100:.2f}%  B/A {res['B/A']:.2f} → 적용비율 {res['적용비율']*100:.2f}%")
    print(f"평균기준소득월액 {res['평균기준소득월액']:,.0f}   A값 {res['A값']:,.0f}")
    for k, v in res["구간별"].items():
        print(f"  {k} {v:>12,.0f}")
    print(f"3기간: 재분배 {res['3기간_상세']['소득재분배산식']:,.0f} vs "
          f"종전 {res['3기간_상세']['종전규정산식']:,.0f} "
          f"→ {'상한 적용' if res['3기간_상세']['역전방지상한적용'] else '재분배 적용'}")
    print(f"월 연금액 {res['월연금']:,.0f}원 ({res['개시연']}년, {res['개시연령']}세부터 / "
          f"무연금 {res['무연금년']}년)")
