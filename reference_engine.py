def load_이행률() -> tuple[list[str], list[list[float | None]]]:
    """행=이후기간(33), 열=종전기간(34). 행 k는 열 k부터 채워진 삼각행렬."""
    rows = list(csv.reader(open(DATA / "이행률표_시행령_부칙_제10조제10항.csv", encoding="utf-8-sig")))
    header, body = rows[0][1:], rows[1:]
    table = [[float(c) if c else None for c in r[1:]] for r in body]
    for k, r in enumerate(table, start=1):
        assert sum(1 for c in r if c is not None) == 35 - k, f"삼각구조 위반: 행 {k}"
    diag = [table[i][i] for i in range(33)]
    assert all(b > a for a, b in zip(diag, diag[1:])), "대각선 단조성 위반"
    새 = [r[33] for r in table]
    assert all(b > a for a, b in zip(새, 새[1:])), "신규자 열 단조성 위반"
    assert (새[0], 새[-1]) == (77.25, 103.44), "신규자 열 범위 불일치"
    return header, table


def load_인상률() -> dict[int, dict[str, float | None]]:
    out = {}
    for r in csv.DictReader(open(DATA / "보수인상률_물가변동률_시계열.csv", encoding="utf-8-sig")):
        f = lambda k: float(r[k]) / 100 if r[k] else None
        out[int(r["연도"])] = {"보수": f("공무원보수인상률(%)"), "물가": f("전국소비자물가변동률(%)"),
                              "연금": f("공무원연금 인상률(%)")}
    for y in range(2021, 2027):
        a, b = out[y]["연금"], out[y - 1]["물가"]
        assert a == b, f"연금인상률(t) != 물가(t-1): {y}"
    return out


def load_평균액() -> dict[int, int]:
    out = {}
    for r in csv.DictReader(open(DATA / "전체공무원_기준소득월액_평균액.csv", encoding="utf-8-sig")):
        if r["평균액(원)"]:
            out[int(r["고시연도"])] = int(r["평균액(원)"])
    assert set(range(2011, 2027)) <= out.keys(), "2011~2026 결측"
    # ★ 단조증가를 가정하지 말 것: 2021년 감소(코로나)
    assert out[2021] < out[2020], "2021년 감소가 사라짐 — 데이터 확인 필요"
    return out


def 이행률조회(table, 종전기간_년: float, 이후기간_년: float) -> float:
    """열 인덱스: 0=32년이상, 1=31~32, ... 31=1~2, 32=1월~1년, 33=신규자"""
    if 종전기간_년 <= 0:
        col = 33
    elif 종전기간_년 < 1:
        col = 32
    elif 종전기간_년 >= 32:
        col = 0
    else:
        col = 32 - int(종전기간_년)          # 1~2년 → 31, 2~3년 → 30 ...
    # 행: '~1년 이하'=0, '1년 초과~2년 이하'=1, ... '32년 초과'=32
    row = min(32, max(0, -(-이후기간_년 // 1) - 1 if 이후기간_년 % 1 == 0 else int(이후기간_년)))
    v = table[int(row)][col]
    if v is None:
        raise ValueError(f"빈 셀: 종전 {종전기간_년}년 + 이후 {이후기간_년}년 (합계 33년 초과)")
    return v / 100


