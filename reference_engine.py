# ─────────────────────────────────────────────────────────────

def 계산(inp: 입력) -> dict:
    g, table = inp.가정, load_이행률()[1]
    평균액 = load_평균액()
    r, p = g.보수인상률, g.물가변동률
    m = r + g.호봉승급기여                       # 기준소득월액 명목 성장률

    퇴직연 = inp.퇴직[0]
    개시연령 = 지급개시연령(퇴직연)
    개시연 = inp.출생연 + 개시연령
    무연금년 = max(0, 개시연 - 퇴직연)

    # ── 재직기간 3분할 ──────────────────────────────────────
    본무 = _월수(inp.임용, inp.퇴직)
    seg = {"1기간": 0, "2기간": 0, "3기간": 0}
    def _배분(s, e):
        for y in range(s[0], e[0] + 1):
            lo = s[1] if y == s[0] else 1
            hi = e[1] if y == e[0] else 12
            k = "1기간" if y <= 2009 else ("2기간" if y <= 2015 else "3기간")
            seg[k] += hi - lo + 1
    _배분(inp.임용, inp.퇴직)
    if inp.군복무:
        _배분(*inp.군복무)
    총월 = sum(seg.values())
    종전 = seg["1기간"] / 12
    이후 = (seg["2기간"] + seg["3기간"]) / 12

    상한 = 재직기간상한(sum(v for k, v in seg.items() if k != "3기간") / 12)
    if 총월 / 12 > 상한:
        총월 = int(상한 * 12)                    # 실제로는 최근 기간부터 절단해야 함

    ih = 이행률조회(table, 종전, 이후)

    # ── 평균기준소득월액 (퇴직시점 → 개시시점 환산) ──────────
    KSW퇴직 = inp.기준소득월액 * (1 + m) ** (퇴직연 - inp.기준연도)
    q = (1 + r) / (1 + m)                        # 과거 연도를 보수인상률로만 환산한 감쇠
    # ★미확정 분기: 군복무 산입기간의 기준소득월액 취급
    #   True  = 재직기간 전체(군복무 포함)를 분모에 → 오래된 달이 늘어 평균이 낮아짐 (보수적)
    #   False = 본무 기간만 평균 산정, 군복무는 재직기간 가산으로만 반영 (유리)
    n = 총월 if inp.군복무_평균산입 else 본무
    B퇴직 = KSW퇴직 * sum(q ** (k / 12) for k in range(n)) / n
    B = B퇴직 * (1 + r) ** (개시연 - 퇴직연)      # 시행령 제10조제2항: 보수인상률

    # ── A값 (법 제30조제2항제1호) ───────────────────────────
    avg = lambda y: 평균액[2026] * (1 + g.평균액인상률) ** (y - 2026) if y > 2026 else 평균액[y]
    A전년 = (avg(퇴직연 - 3) * (1 + p) ** 2 + avg(퇴직연 - 2) * (1 + p) + avg(퇴직연 - 1)) / 3
    A = A전년 * (1 + r) ** (개시연 - (퇴직연 - 1))

    비율 = int(B / A * 100) / 100                # 소수 둘째자리 절사
    적용 = next(v for th, v in 소득재분배구간 if 비율 < th)
    C = B * 적용

    # ── 구간별 급여 ─────────────────────────────────────────
    # 1기간: 20년 미만 → 평균보수월액 × 재직연수 × 2.5%
    평보 = B if inp.일기간소득인정 else 0
    y1 = 평보 * (seg["1기간"] / 12) * 0.025
    # 2기간
    y2 = B * ih * (seg["2기간"] / 12) * 0.019
    # 3기간: 연도별 지급률
    s3 = 0.0
    for y in range(max(2016, inp.임용[0]), 퇴직연 + 1):
        lo = inp.임용[1] if y == inp.임용[0] else 1
        hi = inp.퇴직[1] if y == 퇴직연 else 12
        s3 += (hi - lo + 1) / 12 * (지급률[y] - 1.0) / 100
    재3 = seg["3기간"] / 12
    개인 = B * ih * s3
    재분 = C * ih * min(재3, 소득재분배상한재직년) * 0.01
    개정 = 개인 + 재분
    종전규정 = B * ih * (s3 + 재3 * 0.01)         # 소득재분배 미적용
    y3 = min(개정, 종전규정)                      # ★역전 방지 상한 (부칙)
    상한적용 = 개정 > 종전규정

    월연금 = y1 + y2 + y3

    # ── 조기퇴직연금 ────────────────────────────────────────
    조기 = None
    if inp.조기수령:
        미달 = min(5, 개시연 - max(퇴직연, inp.출생연 + 60))
        if 미달 > 0:
            율 = next(v for k, v in 조기감액 if 미달 <= k)
            수령연 = 개시연 - 미달
            조기 = {"수령개시연": 수령연, "미달연수": 미달, "지급률": 율,
                   "월연금": 월연금 / (1 + r) ** (개시연 - 수령연) * 율}

    return {
        "재직": {"총년": 총월 / 12, **{k: v / 12 for k, v in seg.items()}},
        "이행률": ih, "평균기준소득월액": B, "A값": A, "B/A": 비율, "적용비율": 적용,
        "구간별": {"1기간": y1, "2기간": y2, "3기간": y3},
        "3기간_상세": {"소득재분배산식": 개정, "종전규정산식": 종전규정, "역전방지상한적용": 상한적용},
        "월연금": 월연금, "개시연": 개시연, "개시연령": 개시연령, "무연금년": 무연금년,
        "실질가치_기준연도": 월연금 / (1 + p) ** (개시연 - inp.기준연도),
        "조기퇴직연금": 조기,
    }


