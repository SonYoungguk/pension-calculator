@dataclass
class 가정:
    보수인상률: float = 0.023      # 최근 10년 평균
    물가변동률: float = 0.021
    호봉승급기여: float = 0.015    # 기준소득월액 명목 증가 = 보수인상률 + 이 값
    평균액인상률: float = 0.023    # 실적상 보수인상률과 거의 동일 (2011~2026 CAGR 2.77%)


@dataclass
class 입력:
    출생연: int
    임용: tuple[int, int]              # (연, 월)
    퇴직: tuple[int, int]              # (연, 월) — 퇴직일이 속하는 달
    기준소득월액: int                   # 기준연도 시점
    기준연도: int = 2026
    군복무: tuple[tuple[int, int], tuple[int, int]] | None = None   # ((연,월),(연,월))
    일기간소득인정: bool = True        # ★미확정: 군복무 1기간분 소득 취급
    군복무_평균산입: bool = True       # ★미확정: 군복무 기간을 평균기준소득월액 분모에 넣을지
    조기수령: bool = False
    가정: 가정 = field(default_factory=가정)


def _월수(a: tuple[int, int], b: tuple[int, int]) -> int:
    """a월부터 b월까지 포함 개월수 (법 제25조제1항)."""
    return (b[0] - a[0]) * 12 + (b[1] - a[1]) + 1


